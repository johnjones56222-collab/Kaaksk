FontAtlas buildFontAtlas() {
  FontAtlas a;
  a.pixels.assign(static_cast<size_t>(a.width * a.height), 0);
  for (int g = 0; g < 95; ++g) {
    const int cx = (g % FontAtlas::kCols) * FontAtlas::kCellW;
    const int cy = (g / FontAtlas::kCols) * FontAtlas::kCellH;
    int minCol = 5, maxCol = -1;
    for (int r = 0; r < 8; ++r)
      for (int c = 0; c < 5; ++c)
        if (kGlyphs[g][r][c] == '#') {
          a.pixels[static_cast<size_t>((cy + r) * a.width + cx + c)] = 255;
          if (c < minCol) minCol = c;
          if (c > maxCol) maxCol = c;
        }
    if (maxCol < 0) {  // space
      a.left[g] = 0;
      a.advance[g] = 4;
    } else {
      a.left[g] = minCol;
      a.advance[g] = maxCol - minCol + 2;
    }
  }
  return a;
}

